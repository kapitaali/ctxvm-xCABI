/** The canonical 3-step grouping of the committed parts fixture (same shape the
 * integration test replays: transformParams fires once per start-step group). */
function stepGroups(): Record<string, unknown>[][] {
  const parts = JSON.parse(readFileSync(PARTS_FIXTURE, "utf8")) as Record<string, unknown>[];
  const groups: Record<string, unknown>[][] = [[]];
  for (const part of parts) {
    if (part.type === "start-step") groups.push([part]);
    else (groups[groups.length - 1] as Record<string, unknown>[]).push(part);
  }
  const stepGroups = groups.filter((group) => (group[0] as Record<string, unknown>)?.type === "start-step");
  if ((groups[0] as Record<string, unknown>[]).length > 0) stepGroups[0]!.unshift(...(groups[0] as Record<string, unknown>[]));
  return stepGroups as Record<string, unknown>[][];
}

async function replayGroups(
  capture: ReturnType<typeof createCtxvmCapture>,
  groups: Record<string, unknown>[][],
): Promise<void> {
  for (const group of groups) {
    await capture.middleware.transformParams!({
      type: "stream",
      params: { prompt: [] } as never,
      model: {} as never,
    });
    for await (const _ of capture.tap((async function* () { yield* group; })())) {} // mirror pass-over
  }
}

