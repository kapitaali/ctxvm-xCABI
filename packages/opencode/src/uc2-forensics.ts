/**
 * UC2-MIRROR — forensics surface for the OpenCode plugin lane.
 *
 * Line-for-line TS mirror of `packages/hermes/src/uc2_forensics.py` (the UC2
 * reference implementation): thin per-port wrappers around the committed Rust
 * CLI binaries (`replay`, `profile`, `diff`, `export`) plus the verdict
 * decomposition that separates context-management faults from model reasoning
 * faults. The engine (Rust core) is untouched — this module only shells out to
 * already-built binaries and interprets their JSON output.
 *
 * Parity pins (09-plugin-parity.md §4):
 *   - identical method surfaces and result shapes (`{exit_code, report, stderr}`);
 *   - identical binary resolution order (CTXVM_RUST_BIN_DIR override →
 *     rust/target/release walk-up → PATH) and identical binary-not-found exit law;
 *   - identical `diagnose()` algorithm, verdict vocabulary, and reason strings,
 *     pinned to the shared golden fixture
 *     `packages/opencode/test/fixtures/uc2-diagnose-golden.json` (generated by
 *     the hermes reference) — both sides deep-equal the same fixture.
 *
 * In-harness command reality: the opencode v2.1.2 promise-plugin surface exposes
 * no command-registration hook (only `session.context` +
 * `tool.execute.before|after`), so there is no `/ctxvm-forensics` here — the
 * kit entry `tools/uc2-forensics.sh diagnose <trace> <turn>` is the user-facing
 * surface on this lane (it runs this module's CLI head). In-session forensics
 * ships on the hermes lane via its `/ctxvm-forensics` slash command against the
 * same semantics.
 *
 * Default off: like every UC module, this is behaviorless until called. The
 * feature name mirrors the hermes registry constant (`uc_registry.UC2_FEATURE`);
 * the TS feature-registry dispatcher lands with the UC1 beats (design/uc1-plugin.md B2).
 */

import { spawnSync } from "node:child_process";
import { statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Mirrors `uc_registry.UC2_FEATURE` (packages/hermes/src/uc_registry.py). */
export const UC2_FEATURE = "uc2-forensics";

interface RunResult {
  exit_code: number;
  stdout: string;
  stderr: string;
}

/** Best-effort JSON parse of a binary's stdout; raw string on failure (hermes `_parse_json`). */
function parseJson(stdout: string): unknown {
  try {
    return JSON.parse(stdout) as unknown;
  } catch {
    return stdout as unknown;
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function isFile(path: string): boolean {
  try {
    return statSync(path).isFile();
  } catch {
    return false;
  }
}

function isDir(path: string): boolean {
  try {
    return statSync(path).isDirectory();
  } catch {
    return false;
  }
}

/**
 * Locate the release Rust binaries directory (hermes `_rust_bin_dir`, same order):
 *   1. CTXVM_RUST_BIN_DIR env override
 *   2. rust/target/release/ found by walking up from this module (repo root)
 *   3. null → fall back to PATH lookup
 */
export function rustBinDir(): string | null {
  const override = process.env.CTXVM_RUST_BIN_DIR;
  if (override && isDir(override)) return resolve(override);
  let dir = dirname(fileURLToPath(import.meta.url));
  for (;;) {
    const candidate = join(dir, "rust", "target", "release");
    if (isFile(join(candidate, "replay"))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function binPath(name: string): string {
  const dir = rustBinDir();
  return dir === null ? name : join(dir, name);
}

/** Shell out to a Rust binary; hermes `_run` shape, including the not-found law (exit 2). */
function run(name: string, args: readonly string[]): RunResult {
  const proc = spawnSync(binPath(name), [...args], { encoding: "utf8" });
  if (proc.error) {
    return {
      exit_code: 2,
      stdout: "",
      stderr: `binary not found: ${name} (set CTXVM_RUST_BIN_DIR or add rust/target/release to PATH)`,
    };
  }
  return { exit_code: proc.status ?? 2, stdout: proc.stdout, stderr: proc.stderr };
}

/** Shape shared by every wrapper result (hermes: `{"exit_code", "report", "stderr"}`). */
export interface CliOutcome {
  exit_code: number;
  report: unknown;
  stderr: string;
}

export interface ReplayOptions {
  turn?: number;
  pins?: readonly string[];
  output?: string;
}

export interface ProfileOptions {
  events?: readonly string[];
  turns?: string;
  source?: string;
  output?: string;
}

export interface DiffOptions {
  output?: string;
}

export interface ExportOptions {
  turn?: number;
  output?: string;
  odps?: boolean;
}

export interface DiagnoseEvidence {
  faults_at_turn: readonly unknown[];
  evictions_before: readonly unknown[];
  replay_exit_code: number;
  replay_divergences: readonly unknown[];
}

export interface Diagnosis {
  fault_turn: number;
  verdict: "context-management" | "model-reasoning" | "inconclusive";
  reason: string;
  evidence: DiagnoseEvidence;
}

export class UC2Forensics {
  /** Mirrors the hermes `UCModule` name/feature attributes. */
  static readonly NAME = UC2_FEATURE;
  static readonly FEATURE = UC2_FEATURE;

  readonly name = UC2Forensics.NAME;
  readonly feature = UC2Forensics.FEATURE;

  /** Mirrors `UCModule.enabled` (hermes: `self.feature in features`). */
  enabled(features: ReadonlySet<string>): boolean {
    return features.has(this.feature);
  }

  /** `ctxvm replay <trace> [--turn N] [--pin …] [--output FILE]` — mirrors hermes arg order. */
  replay(trace: string, options: ReplayOptions = {}): CliOutcome {
    const args: string[] = [trace];
    if (options.turn !== undefined) args.push("--turn", String(options.turn));
    if (options.pins) for (const pin of options.pins) args.push("--pin", pin);
    if (options.output) args.push("--output", options.output);
    return this.#finish(run("replay", args));
  }

  /** `ctxvm profile <trace> [--event …] [--turns spec] [--source <src>] [--output FILE]`. */
  profile(trace: string, options: ProfileOptions = {}): CliOutcome {
    const args: string[] = [trace];
    if (options.events) for (const event of options.events) args.push("--event", event);
    if (options.turns) args.push("--turns", options.turns);
    if (options.source) args.push("--source", options.source);
    if (options.output) args.push("--output", options.output);
    return this.#finish(run("profile", args));
  }

  /** `ctxvm diff <a.jsonl> <b.jsonl> [--output FILE]`. */
  diff(a: string, b: string, options: DiffOptions = {}): CliOutcome {
    const args: string[] = [a, b];
    if (options.output) args.push("--output", options.output);
    return this.#finish(run("diff", args));
  }

  /** `ctxvm export <trace> [--turn N] [--output DIR] [--odps]`. */
  export(trace: string, options: ExportOptions = {}): CliOutcome {
    const args: string[] = [trace];
    if (options.turn !== undefined) args.push("--turn", String(options.turn));
    if (options.output) args.push("--output", options.output);
    if (options.odps) args.push("--odps");
    return this.#finish(run("export", args));
  }

  #finish(result: RunResult): CliOutcome {
    return { exit_code: result.exit_code, report: parseJson(result.stdout), stderr: result.stderr };
  }

  /**
   * Diagnose whether a fault at *faultTurn* is context-management or model
   * reasoning — hermes `UC2Forensics.diagnose`, mirrored exactly:
   *   1. `replay --turn N` is the fact gate (must be divergence-free, exit 0);
   *   2. profile all `page.fault` rows at turn N;
   *   3. profile all `page.evict` rows in `0-(N-1)`;
   *   4. a fault whose page was evicted before the turn ⇒ context-management
   *      fault; resident ⇒ model reasoning fault; missing fault at turn or a
   *      dirty fact gate ⇒ inconclusive.
   */
  diagnose(trace: string, faultTurn: number): Diagnosis {
    // Fact gate: replay must be divergence-free at the fault turn.
    const replayResult = this.replay(trace, { turn: faultTurn });
    const replayReport = replayResult.report;
    const divergences =
      isRecord(replayReport) && Array.isArray(replayReport.divergences)
        ? replayReport.divergences
        : [];

    // Faults at the fault turn.
    const profileResult = this.profile(trace, { events: ["page.fault"] });
    const profileReport = profileResult.report;
    const faults =
      isRecord(profileReport) && Array.isArray(profileReport.faults) ? profileReport.faults : [];
    const faultsAtTurn = faults.filter((row) => isRecord(row) && row.turn === faultTurn);

    // Evictions before the fault turn.
    const turnsSpec = faultTurn > 0 ? `0-${faultTurn - 1}` : "0-0";
    const evictResult = this.profile(trace, { events: ["page.evict"], turns: turnsSpec });
    const evictReport = evictResult.report;
    const evictionsBefore =
      isRecord(evictReport) && Array.isArray(evictReport.evictions) ? evictReport.evictions : [];

    const evictedRefs = new Set<unknown>(
      evictionsBefore.filter(isRecord).map((row) => {
        const page = row.page;
        return isRecord(page) ? page.logicalRef : undefined;
      }),
    );

    // Verdict (reason strings are parity — hermes emits the same literals).
    let verdict: Diagnosis["verdict"];
    let reason: string;
    if (faultsAtTurn.length === 0) {
      verdict = "inconclusive";
      reason = `no page.fault at turn ${faultTurn}`;
    } else if (replayResult.exit_code !== 0 || divergences.length > 0) {
      verdict = "inconclusive";
      reason = `replay at turn ${faultTurn} not divergence-free (exit ${replayResult.exit_code})`;
    } else {
      const contextManagement = faultsAtTurn.some((row) => {
        const page = isRecord(row) ? row.page : undefined;
        return isRecord(page) && evictedRefs.has(page.logicalRef);
      });
      verdict = contextManagement ? "context-management" : "model-reasoning";
      reason = contextManagement
        ? "page evicted before fault turn — pager dropped needed content"
        : "page resident at fault turn — pager not at fault";
    }

    return {
      fault_turn: faultTurn,
      verdict,
      reason,
      evidence: {
        faults_at_turn: faultsAtTurn,
        evictions_before: evictionsBefore,
        replay_exit_code: replayResult.exit_code,
        replay_divergences: divergences,
      },
    };
  }
}

// --- kit CLI head (driven by tools/uc2-forensics.sh) ------------------------

function usage(): number {
  process.stderr.write("usage: uc2-forensics.ts diagnose <trace.jsonl> <fault-turn>\n");
  return 2;
}

function cliMain(argv: readonly string[]): number {
  if (argv.length !== 3 || argv[0] !== "diagnose") return usage();
  const turn = Number(argv[2]);
  if (!Number.isInteger(turn)) return usage();
  const diagnosis = new UC2Forensics().diagnose(argv[1], turn);
  process.stdout.write(`${JSON.stringify(diagnosis, null, 2)}\n`);
  return 0;
}

const invoked = process.argv[1] !== undefined ? resolve(process.argv[1]) : "";
if (invoked !== "" && invoked === fileURLToPath(import.meta.url)) {
  process.exitCode = cliMain(process.argv.slice(2));
}
